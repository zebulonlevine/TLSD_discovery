#!/usr/bin/env python3
"""
generate_er_combinations.py

Emit a combinations.yaml that pairs every real condition in an
experiment with four single-member combos, one per ER zone:

  {cond}__all          zone: all          (joint-fit on all trajectories)
  {cond}__on_structure zone: on_structure
  {cond}__on_ER_broad  zone: on_ER_broad
  {cond}__off_ER       zone: off_ER

The __all entry exists so the "all trajectories" joint saSPT fit is
apples-to-apples with the three zone fits. Per-FOV-saSPT aggregation
(what run_conditionwise.py produces) can differ from a joint fit on
pooled trajectories — by ~0.16 log10 D in prior measurements — so a
joint-fit "all" combo is what you want for zone-vs-all comparisons.

Discovers conditions either from existing trajectories under
<analysis_dir>/trajectories/ (preferred — guarantees every emitted
combo has data) or from the raw_data/ ND2 list as a fallback.

Usage:
    python generate_er_combinations.py \\
        --analysis-dir /path/to/tracking_output_q=15p0 \\
        --out /path/to/experiment/combinations.yaml

    # Or discover conditions from raw_data/
    python generate_er_combinations.py \\
        --raw-data-dir /path/to/experiment/raw_data \\
        --out /path/to/experiment/combinations.yaml

    # Restrict to a subset of conditions
    python generate_er_combinations.py --analysis-dir ... --out ... \\
        --conditions "line=L29_degron=000_HHT=000,line=L29_degron=001_HHT=000"

    # Custom suffix separator (default '__')
    python generate_er_combinations.py --analysis-dir ... --out ... \\
        --sep _zone_

Conventions used:
- Combo names: '{condition}__{zone}'. Two underscores are unusual in
  condition names so this is collision-safe. Override with --sep.
- 'all' is emitted as a real combo entry with zone: all. The combination
  pooler treats zone='all' as a no-op alias for the canonical
  trajectories/ directory.
"""

import argparse
import glob
import os
import re
import sys


ZONES = ['all', 'on_structure', 'on_ER_broad', 'off_ER']


def discover_conditions_from_traj(traj_dir):
    """Pull condition names from per-FOV _traj.csv basenames.

    Per-FOV file convention: '{cond}_{NNN}_traj.csv'. Strip the
    '_NNN_traj.csv' tail to get the condition.
    """
    if not os.path.isdir(traj_dir):
        raise SystemExit(f"--analysis-dir/trajectories not found: {traj_dir}")
    files = glob.glob(os.path.join(traj_dir, '*_traj.csv'))
    if not files:
        raise SystemExit(f"No _traj.csv files in {traj_dir}")
    conds = set()
    for f in files:
        base = os.path.basename(f)
        m = re.match(r'(.+?)_\d+_traj\.csv$', base)
        if m:
            conds.add(m.group(1))
        else:
            # Fall back to whole stem if no _NNN tail
            conds.add(re.sub(r'_traj\.csv$', '', base))
    return sorted(conds)


def discover_conditions_from_raw(raw_dir):
    """Pull condition names from raw_data/*.nd2 by trimming the _NNN suffix."""
    if not os.path.isdir(raw_dir):
        raise SystemExit(f"--raw-data-dir not found: {raw_dir}")
    files = sorted(glob.glob(os.path.join(raw_dir, '*.nd2')))
    if not files:
        raise SystemExit(f"No .nd2 files in {raw_dir}")
    conds = set()
    for f in files:
        base = os.path.basename(f)
        m = re.match(r'(.+?)_\d+\.nd2$', base)
        if m:
            conds.add(m.group(1))
        else:
            conds.add(re.sub(r'\.nd2$', '', base))
    return sorted(conds)


def emit_yaml(conditions, sep='__', zones=ZONES):
    """Build the YAML text. Hand-built rather than yaml.dump to keep
    comments and a readable, stable ordering."""
    lines = []
    lines.append('# combinations.yaml — ER 4-zone joint-fit per condition')
    lines.append('# Generated by generate_er_combinations.py')
    lines.append('#')
    lines.append('# Each real condition spawns 4 combos:')
    lines.append("#   {cond}__all          zone: all (no filter; joint-fit on all)")
    lines.append('#   {cond}__on_structure zone: on_structure')
    lines.append('#   {cond}__on_ER_broad  zone: on_ER_broad')
    lines.append('#   {cond}__off_ER       zone: off_ER')
    lines.append('#')
    lines.append('# The pooler reads from trajectories_{zone}/ for filtered')
    lines.append('# zones, and from the canonical trajectories/ for zone: all.')
    lines.append('')
    lines.append('combinations:')
    for cond in conditions:
        for zone in zones:
            combo_name = f"{cond}{sep}{zone}"
            lines.append(f'  {combo_name}:')
            lines.append(f'    conditions: [{cond}]')
            lines.append(f'    zone: {zone}')
        lines.append('')
    return '\n'.join(lines) + '\n'


def main():
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    group = parser.add_mutually_exclusive_group(required=True)
    group.add_argument('--analysis-dir',
                       help='Path to tracking_output_q=*/ (will look in '
                            'trajectories/ for *_traj.csv to discover conditions).')
    group.add_argument('--raw-data-dir',
                       help='Path to raw_data/ as a fallback discovery source.')

    parser.add_argument('--out', required=True,
                        help='Path to write combinations.yaml.')
    parser.add_argument('--conditions',
                        help='Comma-separated condition names to restrict to. '
                             'If omitted, all discovered conditions are used.')
    parser.add_argument('--sep', default='__',
                        help="Separator between condition and zone in combo "
                             "names (default '__').")
    parser.add_argument('--zones', default=','.join(ZONES),
                        help=f"Comma-separated zones to emit (default: {','.join(ZONES)})")
    parser.add_argument('--force', action='store_true',
                        help='Overwrite --out if it already exists.')

    args = parser.parse_args()

    if args.analysis_dir:
        traj_dir = os.path.join(args.analysis_dir, 'trajectories')
        conditions = discover_conditions_from_traj(traj_dir)
        src = traj_dir
    else:
        conditions = discover_conditions_from_raw(args.raw_data_dir)
        src = args.raw_data_dir

    if args.conditions:
        wanted = {c.strip() for c in args.conditions.split(',')}
        missing = wanted - set(conditions)
        if missing:
            print(f"WARNING: requested conditions not found in {src}: "
                  f"{sorted(missing)}", file=sys.stderr)
        conditions = [c for c in conditions if c in wanted]

    if not conditions:
        raise SystemExit("No conditions to emit. Aborting.")

    zones = [z.strip() for z in args.zones.split(',')]
    unknown = set(zones) - set(ZONES)
    if unknown:
        print(f"WARNING: emitting non-standard zones: {sorted(unknown)}. "
              f"They must correspond to existing trajectories_{{zone}}/ "
              f"directories at combinationwise time.", file=sys.stderr)

    if os.path.exists(args.out) and not args.force:
        raise SystemExit(
            f"{args.out} already exists. Pass --force to overwrite, or "
            f"choose a different --out path.")

    text = emit_yaml(conditions, sep=args.sep, zones=zones)
    with open(args.out, 'w') as f:
        f.write(text)

    print(f"Discovered {len(conditions)} condition(s) from {src}")
    print(f"Emitted {len(conditions) * len(zones)} combinations "
          f"({len(conditions)} conditions × {len(zones)} zones) "
          f"to {args.out}")


if __name__ == '__main__':
    main()
